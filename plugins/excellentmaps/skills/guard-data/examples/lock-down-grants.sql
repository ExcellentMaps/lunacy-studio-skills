-- ── ЗАПУСК ─────────────────────────────────────────────────────────────
--   psql "postgresql://ПОЛЬЗОВАТЕЛЬ@ХОСТ:5432/БАЗА" -f lock-down-grants.sql
--   Supabase: SQL Editor -> вставить целиком -> прочитать -> Run
-- Запускать от роли, которая владеет схемой и объектами в ней: обычная
-- роль приложения не снимет права с чужих объектов и тихо ничего не сделает.

-- ═══ ШАГ 0. ПОДГОТОВКА ═════════════════════════════════════════════════

-- Всё выполняется одной транзакцией: либо применяется целиком, либо не
-- применяется вовсе. Пока не дошли до COMMIT, можно сказать ROLLBACK;
begin;

-- Не даём скрипту висеть, если таблица занята: лучше честно упасть
-- по таймауту, чем держать блокировку на боевой базе.
set local lock_timeout = '5s';

-- ⚠️ Если ваши таблицы лежат в схеме public — будьте особенно осторожны:
-- там же живут служебные объекты и объекты расширений, и снятие прав задевает
-- больше, чем вы ожидаете. Решение — перенести свои объекты в отдельную схему.

-- ═══ ШАГ 1. ЗАБРАТЬ ОБЩИЕ ПРАВА ════════════════════════════════════════
-- Порядок именно такой: сначала забрать всё, потом выдать точечно.
-- Обратный порядок означает, что каждая НОВАЯ таблица открывается наружу
-- автоматически. Подробнее — references/rls-and-grants.md, раздел 2.

-- Роль public — это НЕ «неавторизованный пользователь», а «все роли сразу»:
-- права, выданные сюда, получают и anon, и authenticated. Начинаем с неё.
revoke all on schema healing from public;

-- usage on schema — только право «знать, что схема существует». Доступа
-- к данным не даёт, но без него не работает ничего, включая вызов функций.
grant usage on schema healing to anon, authenticated;

-- Прямой доступ к таблицам закрываем полностью: приложение должно ходить
-- в базу через функции (ШАГ 4), а функция сама проверяет, кто её вызвал.
revoke all on all tables in schema healing from public, anon, authenticated;

-- Последовательности (генераторы id). Прочитать данные через них нельзя,
-- но можно сдвинуть счётчик и получить конфликты при вставке.
revoke all on all sequences in schema healing from public, anon, authenticated;

-- Функции. По умолчанию PostgreSQL выдаёт право выполнения ВСЕМ — это
-- поведение базы, а не чья-то ошибка. Выдадим заново поимённо в ШАГЕ 4.
revoke all on all functions in schema healing from public, anon, authenticated;

-- Правило для БУДУЩИХ объектов. Без него следующая созданная функция снова
-- окажется доступной всем, и зачистка проживёт до ближайшей миграции.
alter default privileges in schema healing revoke all on functions from public;
alter default privileges in schema healing revoke all on tables    from public;

-- ═══ ШАГ 2. ВКЛЮЧИТЬ ЗАЩИТУ НА УРОВНЕ СТРОК ════════════════════════════
-- Второй рубеж: даже если права на таблицу кто-то выдаст по ошибке, без
-- подходящей политики строки не отдадутся. Таблица с включённым RLS и БЕЗ
-- политик не отдаёт ничего никому, кроме владельца, — ровно то, что нужно
-- при доступе через функции security definer.

do $$
declare t record;
begin
  -- Только обычные таблицы: relkind = 'r'. Вьюхи, индексы
  -- и последовательности сюда не попадают.
  for t in
    select c.relname
      from pg_class c
      join pg_namespace n on n.oid = c.relnamespace
     where n.nspname = 'healing'
       and c.relkind = 'r'
       and not c.relrowsecurity       -- только те, где ещё не включено
  loop
    execute format('alter table healing.%I enable row level security', t.relname);
    raise notice 'RLS включён: %', t.relname;
  end loop;
end $$;

-- ⚠️ Если приложение читает таблицы НАПРЯМУЮ (без функций), эта команда
-- мгновенно оставит его без данных: в таком проекте сначала пишутся
-- политики, и только потом включается RLS. Правила их написания —
-- references/rls-and-grants.md, раздел 3.

-- ═══ ШАГ 3. ЗАКРЕПИТЬ search_path У SECURITY DEFINER ═══════════════════
-- Автоматически это сделать нельзя: у каждой функции свой набор схем.
-- Запрос ниже покажет проблемные. Каждую правьте в её файле миграции,
-- дописывая:  set search_path = healing, pg_temp
-- Почему это обязательно — references/rls-and-grants.md, раздел 4.

select n.nspname as "схема",
       p.proname as "функция — добавить set search_path"
  from pg_proc p
  join pg_namespace n on n.oid = p.pronamespace
 where p.prosecdef
   and n.nspname = 'healing'
   and (p.proconfig is null
        or not exists (select 1 from unnest(p.proconfig) cfg
                        where cfg like 'search\_path=%'));

-- ═══ ШАГ 4. ВЫДАТЬ ПРАВА ТОЧЕЧНО ═══════════════════════════════════════
--
-- ⚠️ НИЖЕ — ПРИМЕР ИЗ ЧУЖОГО ПРОЕКТА. ЗАМЕНИТЕ ЕГО СВОИМ СПИСКОМ.
--
-- Как собрать свой список, не гадая:
--   1. Найдите в коде все вызовы функций базы (в Supabase это .rpc(...)).
--   2. Выпишите имена — это и есть полный список того, что должно быть
--      открыто. Больше ничего открывать не нужно.
--   3. Уточните ПОЛНУЮ подпись каждой с типами аргументов:  \df healing.*
--      Без точных типов grant молча не сработает на нужной перегрузке.
--
-- Три правила: указывается полная подпись с типами; служебные функции
-- наружу НЕ выдаются; каждая открытая функция обязана САМА проверять
-- вызывающего — открыв её роли anon, вы открыли её всему интернету.

grant execute on function healing.login(text, text)                    to anon;
grant execute on function healing.team(int, uuid)                      to anon;
grant execute on function healing.rename_user(int, uuid, int, text)    to anon;
grant execute on function healing.clients_list(int, uuid, text, text)  to anon;
grant execute on function healing.client_save(int, uuid, json)         to anon;

-- Внутренние функции проверки доступа — healing._auth(int, uuid)
-- и healing._auth_clients(int, uuid) — наружу не выдаются намеренно:
-- открыть их значит отдать проверку доступа тому, кого проверяют.

-- ═══ ШАГ 5. ПРОВЕРКА: ЧТО ОСТАЛОСЬ ОТКРЫТО ═════════════════════════════
-- Выполняется ДО фиксации — чтобы увидеть результат и при необходимости
-- сказать ROLLBACK вместо COMMIT. Первые два запроса должны вернуть ПУСТО,
-- третий — ровно ваш список из ШАГА 4, строка в строку.

-- 5.1. Таблицы и вьюхи, доступные публичным ролям. Должно быть пусто.
select grantee      as "кому",
       table_name   as "таблица/вьюха",
       string_agg(distinct privilege_type, ', ' order by privilege_type) as "права"
  from information_schema.role_table_grants
 where grantee in ('anon','authenticated','PUBLIC','public')
   and table_schema = 'healing'
 group by 1,2
 order by 2;

-- 5.2. Таблицы без защиты на уровне строк. Должно быть пусто.
select c.relname as "таблица без RLS"
  from pg_class c
  join pg_namespace n on n.oid = c.relnamespace
 where n.nspname = 'healing' and c.relkind = 'r' and not c.relrowsecurity
 order by 1;

-- 5.3. Функции, доступные снаружи. Каждая лишняя строка здесь — дверь.
select r.routine_name as "функция", r.grantee as "кому",
       case when p.prosecdef then 'DEFINER (полные права)' else 'INVOKER' end as "режим"
  from information_schema.routine_privileges r
  left join pg_proc p      on p.proname = r.routine_name
  left join pg_namespace n on n.oid = p.pronamespace and n.nspname = r.routine_schema
 where r.grantee in ('anon','authenticated','PUBLIC','public')
   and r.routine_schema = 'healing'
 order by 1, 2;

-- ═══ ШАГ 6. ФИКСАЦИЯ ═══════════════════════════════════════════════════
-- Посмотрели результаты ШАГА 5?
--   Всё как ожидалось -> раскомментируйте commit;
--   Что-то не так     -> оставьте rollback; и разбирайтесь.
-- Строка commit намеренно закомментирована: скрипт не меняет права без
-- вашего осознанного действия.

-- commit;
rollback;

